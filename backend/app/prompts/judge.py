"""Промпт судьи: задача + критерии + ответы под случайными номерами.

Тексты вынесены сюда, чтобы их можно было менять и локализовать в одном месте.
"""
from __future__ import annotations

from collections.abc import Sequence

JUDGE_SYSTEM_PROMPT = (
    "Ты — строгий и беспристрастный судья. Оцениваешь несколько ответов на одну "
    "и ту же задачу и выбираешь лучший. Суди только по содержанию ответов и "
    "заданным критериям; порядок ответов случаен и не имеет значения. "
    "Отвечай строго валидным JSON без пояснений вокруг."
)


def build_judge_prompt(
    task: str,
    criteria: Sequence[str],
    answers: Sequence[tuple[int, str]],
) -> str:
    """Собрать промпт судьи. answers — список пар (номер, текст ответа)."""
    numbered = "\n".join(f"### Ответ {number}\n{text}\n" for number, text in answers)
    criteria_text = ", ".join(criteria)
    return (
        "Задача, на которую отвечали участники:\n"
        '"""\n'
        f"{task}\n"
        '"""\n\n'
        f"Критерии оценки: {criteria_text}. Оцени каждый ответ по каждому "
        "критерию и выставь общий балл от 0 до 10 (10 — лучший).\n\n"
        "Ответы участников в случайном порядке:\n\n"
        f"{numbered}\n"
        "Верни ТОЛЬКО валидный JSON этой структуры:\n"
        "{\n"
        '  "winner_id": <номер лучшего ответа>,\n'
        '  "scores": [{"id": <номер ответа>, "score": <число 0..10>, '
        '"reason": "<кратко>", ... для каждого ответа}],\n'
        '  "rationale": "<обоснование выбора, 1-3 предложения>"\n'
        "}\n"
        "Никакого markdown, никакого текста до или после JSON."
    )
